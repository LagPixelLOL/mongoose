//! systemd unit management for `mongoose setup`, `remove` and `show`.
//!
//! "The unit" is whichever `mongoose.service` systemd would load from its
//! search path. A unit written by `setup` (recognised by [`MARKER`]) is
//! replaced or removed in place, wherever it lives. Other units are only
//! touched with `--force`, and only when they are clearly removable: a
//! regular text file with a single link, not on temporary storage and not
//! immutable. New units are written to [`DEFAULT_UNIT_DIR`]. More than one
//! `mongoose.service`, or any drop-in directory, is always refused.

use std::collections::HashSet;
use std::fmt;
use std::fs;
use std::io::{self, Write};
use std::os::unix::fs::{MetadataExt, OpenOptionsExt};
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

use log::{debug, info, warn};
use thiserror::Error;

use crate::spec::ForwardSpec;
use crate::sys::Storage;
use crate::unitfile::{self, ParsedUnit};

pub const UNIT_NAME: &str = "mongoose.service";
pub const DROP_IN_DIR_NAME: &str = "mongoose.service.d";
/// Where new units are written.
pub const DEFAULT_UNIT_DIR: &str = "/etc/systemd/system";
/// systemd's search path for system units, highest priority first
/// (systemd.unit(5)); `/lib/systemd/system` for systems without merged /usr.
pub const UNIT_SEARCH_PATH: &[&str] = &[
    "/etc/systemd/system.control",
    "/run/systemd/system.control",
    "/run/systemd/transient",
    "/run/systemd/generator.early",
    "/etc/systemd/system",
    "/etc/systemd/system.attached",
    "/run/systemd/system",
    "/run/systemd/system.attached",
    "/run/systemd/generator",
    "/usr/local/lib/systemd/system",
    "/usr/lib/systemd/system",
    "/lib/systemd/system",
    "/run/systemd/generator.late",
];
/// First line of every unit written by `mongoose setup`; used to recognise
/// units this tool may replace or remove without `--force`.
pub const MARKER: &str = "# Generated by `mongoose setup`. Managed automatically; do not edit.";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum UnitConflictKind {
    /// One of several `mongoose.service` files in the search path.
    OtherUnit,
    /// A `mongoose.service.d` drop-in directory.
    DropIn,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UnitConflict {
    pub path: PathBuf,
    pub kind: UnitConflictKind,
}

impl fmt::Display for UnitConflict {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self.kind {
            UnitConflictKind::OtherUnit => write!(
                f,
                "{}: one of several {UNIT_NAME} files; only one may exist in the systemd search path",
                self.path.display()
            ),
            UnitConflictKind::DropIn => write!(
                f,
                "{}: drop-in directory that would alter the unit",
                self.path.display()
            ),
        }
    }
}

#[derive(Debug, Error)]
pub enum ServiceError {
    #[error("this command must be run as root")]
    NotRoot,
    #[error("systemd does not appear to be running on this system")]
    NoSystemd,
    #[error("{0} was not written by `mongoose setup`; use --force to replace or remove it anyway")]
    NotManaged(PathBuf),
    #[error("no {UNIT_NAME} found in the systemd search path; nothing to remove")]
    NotInstalled,
    #[error("conflicting systemd configuration, resolve it first:{}", list(.0))]
    Conflicts(Vec<UnitConflict>),
    #[error("--force does not apply to {path}: it {reason}")]
    ForceNotAllowed { path: PathBuf, reason: String },
    #[error("{path} cannot be modified: {reason}")]
    Unmodifiable { path: PathBuf, reason: String },
    #[error("{0} is not a usable executable path")]
    InvalidExecutable(PathBuf),
    #[error("{path}: {error}")]
    Io { path: PathBuf, error: io::Error },
    #[error("`systemctl {command}` failed: {detail}")]
    Systemctl { command: String, detail: String },
}

fn list(conflicts: &[UnitConflict]) -> String {
    conflicts.iter().map(|c| format!("\n  {c}")).collect()
}

fn io_error(path: &Path) -> impl FnOnce(io::Error) -> ServiceError + '_ {
    move |error| ServiceError::Io {
        path: path.to_path_buf(),
        error,
    }
}

/// Access to the parts of the host system the service manager needs.
pub trait System {
    fn is_root(&self) -> bool;
    fn uses_systemd(&self) -> bool;
    /// Runs `systemctl` with `args`, returning its stdout.
    fn systemctl(&self, args: &[&str]) -> Result<String, ServiceError>;
    /// Whether IPv6 sockets are dual-stack by default (for rule descriptions).
    fn ipv6_dual_stack(&self) -> bool;
    /// Filesystem properties of `path`.
    fn storage(&self, path: &Path) -> io::Result<Storage>;
    /// Whether `path` is immutable or append-only (`chattr +i`/`+a`).
    fn is_immutable(&self, path: &Path) -> io::Result<bool>;
}

/// The real host system.
pub struct HostSystem;

impl System for HostSystem {
    fn is_root(&self) -> bool {
        crate::sys::is_root()
    }

    fn ipv6_dual_stack(&self) -> bool {
        crate::sys::ipv6_dual_stack_default()
    }

    fn storage(&self, path: &Path) -> io::Result<Storage> {
        crate::sys::storage(path)
    }

    fn is_immutable(&self, path: &Path) -> io::Result<bool> {
        crate::sys::is_immutable(path)
    }

    fn uses_systemd(&self) -> bool {
        // Same check as sd_booted(3), plus systemctl must be available.
        Path::new("/run/systemd/system").is_dir()
            && Command::new("systemctl")
                .arg("--version")
                .stdout(Stdio::null())
                .stderr(Stdio::null())
                .status()
                .is_ok_and(|status| status.success())
    }

    fn systemctl(&self, args: &[&str]) -> Result<String, ServiceError> {
        let command = args.join(" ");
        debug!("running systemctl {command}");
        let output = Command::new("systemctl")
            .args(args)
            .stdin(Stdio::null())
            .output()
            .map_err(|err| ServiceError::Systemctl {
                command: command.clone(),
                detail: err.to_string(),
            })?;
        let stdout = String::from_utf8_lossy(&output.stdout).into_owned();
        for line in String::from_utf8_lossy(&output.stderr).lines() {
            debug!("systemctl: {line}");
        }
        if output.status.success() {
            Ok(stdout)
        } else {
            let stderr = String::from_utf8_lossy(&output.stderr).trim().to_string();
            Err(ServiceError::Systemctl {
                command,
                detail: if stderr.is_empty() {
                    output.status.to_string()
                } else {
                    stderr
                },
            })
        }
    }
}

/// Returns true if `contents` is a unit written by `mongoose setup`.
pub fn is_managed(contents: &str) -> bool {
    contents.lines().next() == Some(MARKER)
}

/// Quotes a single ExecStart argument following systemd's syntax.
pub fn quote_exec_arg(arg: &str) -> String {
    let escaped = arg.replace('%', "%%").replace('$', "$$");
    let plain = !escaped.is_empty()
        && escaped
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || "/._-:[]*+,@=%$".contains(c));
    if plain {
        return escaped;
    }
    let mut quoted = String::with_capacity(escaped.len() + 2);
    quoted.push('"');
    for c in escaped.chars() {
        match c {
            '"' => quoted.push_str("\\\""),
            '\\' => quoted.push_str("\\\\"),
            '\n' => quoted.push_str("\\n"),
            '\t' => quoted.push_str("\\t"),
            c => quoted.push(c),
        }
    }
    quoted.push('"');
    quoted
}

/// Renders the unit file. Only non-default settings are written.
pub fn render_unit(exe: &Path, specs: &[ForwardSpec]) -> String {
    let mut exec = vec![quote_exec_arg(&exe.to_string_lossy()), "start".to_string()];
    exec.extend(specs.iter().map(|spec| quote_exec_arg(&spec.to_string())));
    format!(
        "{MARKER}\n\
         [Unit]\n\
         Description=Mongoose port forwarder\n\
         Wants=network-online.target\n\
         After=network-online.target\n\
         \n\
         [Service]\n\
         ExecStart={}\n\
         Restart=always\n\
         RestartSec=3\n\
         \n\
         [Install]\n\
         WantedBy=multi-user.target\n",
        exec.join(" ")
    )
}

/// What `setup` does with the unit file.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SetupOutcome {
    /// No unit existed; a new one is written to the default directory.
    Installed,
    /// A unit written by `setup` is replaced in place.
    Replaced,
    /// A unit not written by `setup` is replaced in place (`--force`).
    ReplacedForeign,
}

/// Where and how `setup` writes the unit.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SetupPlan {
    pub path: PathBuf,
    pub outcome: SetupOutcome,
}

/// Who wrote an existing unit file.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Ownership {
    Managed,
    Foreign,
}

pub struct ServiceManager<S> {
    system: S,
    default_dir: PathBuf,
    search_path: Vec<PathBuf>,
}

impl ServiceManager<HostSystem> {
    /// Manager for the real system using systemd's standard paths.
    pub fn host() -> Self {
        Self::new(HostSystem, DEFAULT_UNIT_DIR)
            .with_search_path(UNIT_SEARCH_PATH.iter().map(PathBuf::from).collect())
    }
}

impl<S: System> ServiceManager<S> {
    /// A manager writing new units to `default_dir`, which is also the only
    /// directory searched until [`Self::with_search_path`] or
    /// [`Self::with_other_unit_dirs`] is used.
    pub fn new(system: S, default_dir: impl Into<PathBuf>) -> Self {
        let default_dir = default_dir.into();
        Self {
            system,
            search_path: vec![default_dir.clone()],
            default_dir,
        }
    }

    /// Sets the full search path, highest priority first. The default
    /// directory is added in front if missing.
    pub fn with_search_path(mut self, dirs: Vec<PathBuf>) -> Self {
        self.search_path = dirs;
        if !self.search_path.contains(&self.default_dir) {
            self.search_path.insert(0, self.default_dir.clone());
        }
        self
    }

    /// Searches `dirs` after the default directory.
    pub fn with_other_unit_dirs(self, dirs: Vec<PathBuf>) -> Self {
        let mut path = vec![self.default_dir.clone()];
        path.extend(dirs);
        self.with_search_path(path)
    }

    pub fn system(&self) -> &S {
        &self.system
    }

    /// Where a new unit is written.
    pub fn default_unit_path(&self) -> PathBuf {
        self.default_dir.join(UNIT_NAME)
    }

    fn check_environment(&self) -> Result<(), ServiceError> {
        if !self.system.is_root() {
            return Err(ServiceError::NotRoot);
        }
        if !self.system.uses_systemd() {
            return Err(ServiceError::NoSystemd);
        }
        Ok(())
    }

    /// Existing entries called `name` in search path order. The same file
    /// reached through several paths (e.g. `/lib` -> `/usr/lib`) is listed
    /// once.
    fn find_entries(&self, name: &str) -> Vec<PathBuf> {
        let mut seen = HashSet::new();
        let mut found = Vec::new();
        for dir in &self.search_path {
            let path = dir.join(name);
            if let Ok(meta) = fs::symlink_metadata(&path)
                && seen.insert((meta.dev(), meta.ino()))
            {
                found.push(path);
            }
        }
        found
    }

    /// All `mongoose.service` files, highest priority (the one systemd
    /// loads) first.
    pub fn find_units(&self) -> Vec<PathBuf> {
        self.find_entries(UNIT_NAME)
    }

    /// Drop-ins, plus every unit file shadowed by the one systemd loads.
    pub fn find_conflicts(&self) -> Vec<UnitConflict> {
        let mut conflicts: Vec<_> = self
            .find_units()
            .into_iter()
            .skip(1)
            .map(|path| UnitConflict {
                path,
                kind: UnitConflictKind::OtherUnit,
            })
            .collect();
        conflicts.extend(self.find_entries(DROP_IN_DIR_NAME).into_iter().map(|path| {
            UnitConflict {
                path,
                kind: UnitConflictKind::DropIn,
            }
        }));
        conflicts
    }

    /// The single unit file, if any. Several unit files are refused: which
    /// one counts would depend on systemd's directory priorities.
    fn the_unit(&self) -> Result<Option<PathBuf>, ServiceError> {
        let units = self.find_units();
        if units.len() > 1 {
            return Err(ServiceError::Conflicts(
                units
                    .into_iter()
                    .map(|path| UnitConflict {
                        path,
                        kind: UnitConflictKind::OtherUnit,
                    })
                    .collect(),
            ));
        }
        Ok(units.into_iter().next())
    }

    fn ownership(path: &Path) -> Ownership {
        // Units written by setup are always regular files.
        let regular = fs::symlink_metadata(path).is_ok_and(|meta| meta.file_type().is_file());
        match unitfile::read_unit_text(path) {
            Ok(text) if regular && is_managed(&text) => Ownership::Managed,
            _ => Ownership::Foreign,
        }
    }

    /// `--force` only applies to units that are clearly removable.
    fn check_force_allowed(&self, path: &Path) -> Result<(), ServiceError> {
        let deny = |reason: String| {
            Err(ServiceError::ForceNotAllowed {
                path: path.to_path_buf(),
                reason,
            })
        };
        let meta = fs::symlink_metadata(path).map_err(io_error(path))?;
        if meta.file_type().is_symlink() {
            return deny("is a symlink (e.g. a masked unit or a link to another file)".into());
        }
        if !meta.is_file() {
            return deny("is not a regular file".into());
        }
        if meta.nlink() > 1 {
            return deny(format!("has {} hard links", meta.nlink()));
        }
        if let Err(reason) = unitfile::read_unit_text(path) {
            return deny(reason);
        }
        Ok(())
    }

    /// Checks up front that `path` can be written (and, if it exists,
    /// replaced or deleted), so nothing is left half done, and that the
    /// result would survive a reboot.
    fn check_modifiable(&self, path: &Path, exists: bool) -> Result<(), ServiceError> {
        let refuse = |reason: String| {
            Err(ServiceError::Unmodifiable {
                path: path.to_path_buf(),
                reason,
            })
        };
        let dir = path.parent().unwrap_or(Path::new("/"));
        let storage = self.system.storage(dir).map_err(io_error(dir))?;
        if storage.temporary {
            return refuse(
                "it is on temporary storage (tmpfs), so it would not survive a reboot".into(),
            );
        }
        if storage.read_only {
            return refuse("it is on a read-only filesystem".into());
        }
        if self.system.is_immutable(dir).map_err(io_error(dir))? {
            return refuse(format!("{} is immutable or append-only", dir.display()));
        }
        if exists {
            let meta = fs::symlink_metadata(path).map_err(io_error(path))?;
            if meta.file_type().is_file() {
                if crate::sys::is_mount_point(path).map_err(io_error(path))? {
                    return refuse("it is a mount point".into());
                }
                if self.system.is_immutable(path).map_err(io_error(path))? {
                    return refuse("it is immutable or append-only".into());
                }
            }
        }
        Ok(())
    }

    /// Runs every check `setup` performs before touching anything and
    /// returns where the unit would be written.
    pub fn precheck_setup(&self, exe: &Path, force: bool) -> Result<SetupPlan, ServiceError> {
        self.check_environment()?;
        if !exe.is_absolute() || !exe.is_file() {
            return Err(ServiceError::InvalidExecutable(exe.to_path_buf()));
        }
        let mut conflicts: Vec<_> = self
            .find_entries(DROP_IN_DIR_NAME)
            .into_iter()
            .map(|path| UnitConflict {
                path,
                kind: UnitConflictKind::DropIn,
            })
            .collect();
        match self.the_unit() {
            Err(ServiceError::Conflicts(units)) => conflicts.extend(units),
            Err(err) => return Err(err),
            Ok(_) => {}
        }
        if !conflicts.is_empty() {
            return Err(ServiceError::Conflicts(conflicts));
        }
        let plan = match self.the_unit()? {
            None => SetupPlan {
                path: self.default_unit_path(),
                outcome: SetupOutcome::Installed,
            },
            Some(path) => match Self::ownership(&path) {
                Ownership::Managed => SetupPlan {
                    path,
                    outcome: SetupOutcome::Replaced,
                },
                Ownership::Foreign if force => {
                    self.check_force_allowed(&path)?;
                    SetupPlan {
                        path,
                        outcome: SetupOutcome::ReplacedForeign,
                    }
                }
                Ownership::Foreign => return Err(ServiceError::NotManaged(path)),
            },
        };
        self.check_modifiable(&plan.path, plan.outcome != SetupOutcome::Installed)?;
        Ok(plan)
    }

    /// Writes the unit and, unless `skip_enable`, reloads systemd, enables
    /// the unit and (re)starts it (restarting a running service, so it uses
    /// the new rules). With `skip_enable` nothing else is done; a running
    /// service keeps its previous rules, which is pointed out in the log.
    pub fn setup(
        &self,
        exe: &Path,
        specs: &[ForwardSpec],
        skip_enable: bool,
        force: bool,
    ) -> Result<SetupPlan, ServiceError> {
        let plan = self.precheck_setup(exe, force)?;
        let path = &plan.path;
        let running = skip_enable && self.is_running()?;
        match plan.outcome {
            SetupOutcome::Installed => {}
            SetupOutcome::Replaced => info!("replacing existing unit {}", path.display()),
            SetupOutcome::ReplacedForeign => warn!(
                "replacing {}, which was not written by `mongoose setup` (--force)",
                path.display()
            ),
        }

        write_atomically(path, &render_unit(exe, specs))?;
        info!("wrote {}", path.display());

        if skip_enable {
            info!("skipping systemd reload and enabling {UNIT_NAME}");
            if running {
                warn!(
                    "{UNIT_NAME} is running and keeps using its previous rules; apply the new \
                     ones with `systemctl daemon-reload && systemctl restart {UNIT_NAME}`"
                );
            }
            return Ok(plan);
        }
        self.system.systemctl(&["daemon-reload"])?;
        self.system.systemctl(&["enable", UNIT_NAME])?;
        // restart also starts a stopped unit and applies a replaced config.
        self.system.systemctl(&["restart", UNIT_NAME])?;
        info!("{UNIT_NAME} enabled and started");
        Ok(plan)
    }

    /// Whether the service is running, or about to run again (e.g. waiting to
    /// be restarted after a failure).
    fn is_running(&self) -> Result<bool, ServiceError> {
        let state =
            self.system
                .systemctl(&["show", UNIT_NAME, "--property=ActiveState", "--value"])?;
        Ok(matches!(
            state.trim(),
            "active" | "activating" | "reloading"
        ))
    }

    /// Runs every check `remove` performs before touching anything and
    /// returns the unit file that would be deleted.
    pub fn precheck_remove(&self, force: bool) -> Result<PathBuf, ServiceError> {
        self.check_environment()?;
        // With several unit files, another one would take over once this
        // one is gone.
        let path = self.the_unit()?.ok_or(ServiceError::NotInstalled)?;
        match Self::ownership(&path) {
            Ownership::Managed => {}
            Ownership::Foreign if force => self.check_force_allowed(&path)?,
            Ownership::Foreign => return Err(ServiceError::NotManaged(path)),
        }
        self.check_modifiable(&path, true)?;
        // Drop-ins are merely left orphaned, which is harmless.
        for drop_in in self.find_entries(DROP_IN_DIR_NAME) {
            warn!(
                "{}: drop-in directory not managed by mongoose; it will be left in place",
                drop_in.display()
            );
        }
        Ok(path)
    }

    /// Stops, disables and deletes the unit.
    pub fn remove(&self, force: bool) -> Result<PathBuf, ServiceError> {
        let path = self.precheck_remove(force)?;
        if Self::ownership(&path) == Ownership::Foreign {
            warn!(
                "removing {}, which was not written by `mongoose setup` (--force)",
                path.display()
            );
        }
        self.system.systemctl(&["stop", UNIT_NAME])?;
        self.system.systemctl(&["disable", UNIT_NAME])?;
        fs::remove_file(&path).map_err(io_error(&path))?;
        info!("removed {}", path.display());
        self.system.systemctl(&["daemon-reload"])?;
        Ok(path)
    }
}

fn write_atomically(path: &Path, contents: &str) -> Result<(), ServiceError> {
    let tmp = path.with_extension("service.tmp");
    let mut file = fs::OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(true)
        .mode(0o644)
        .open(&tmp)
        .map_err(io_error(&tmp))?;
    file.write_all(contents.as_bytes())
        .and_then(|()| file.sync_all())
        .map_err(io_error(&tmp))?;
    drop(file);
    fs::rename(&tmp, path).map_err(io_error(path))
}

/// Splits a systemd command line into arguments, undoing [`quote_exec_arg`].
/// Only the syntax `quote_exec_arg` produces is accepted.
pub fn split_exec_args(line: &str) -> Result<Vec<String>, String> {
    let mut args = Vec::new();
    let mut chars = line.chars().peekable();
    loop {
        while chars.next_if(|c| c.is_ascii_whitespace()).is_some() {}
        let Some(&first) = chars.peek() else {
            return Ok(args);
        };
        let mut arg = String::new();
        let quoted = first == '"';
        if quoted {
            chars.next();
        }
        loop {
            let c = match chars.next() {
                None if quoted => return Err("unterminated quote".to_string()),
                None => break,
                Some(c) => c,
            };
            match c {
                '"' if quoted => {
                    if chars.peek().is_some_and(|c| !c.is_ascii_whitespace()) {
                        return Err("unexpected text after closing quote".to_string());
                    }
                    break;
                }
                c if !quoted && c.is_ascii_whitespace() => break,
                '\\' if quoted => match chars.next() {
                    Some('"') => arg.push('"'),
                    Some('\\') => arg.push('\\'),
                    Some('n') => arg.push('\n'),
                    Some('t') => arg.push('\t'),
                    other => return Err(format!("unsupported escape \\{}", other.unwrap_or(' '))),
                },
                '%' | '$' => {
                    if chars.next() != Some(c) {
                        return Err(format!("unsupported '{c}' expansion"));
                    }
                    arg.push(c);
                }
                '"' | '\'' | '\\' | ';' => return Err(format!("unexpected '{c}'")),
                c => arg.push(c),
            }
        }
        args.push(arg);
    }
}

/// Extracts the executable and rules from a unit written by [`render_unit`].
pub fn parse_unit(contents: &str) -> Result<(PathBuf, Vec<ForwardSpec>), String> {
    let mut section = "";
    let mut exec_lines = Vec::new();
    for line in contents.lines() {
        let line = line.trim();
        if line.starts_with('[') && line.ends_with(']') {
            section = line;
        } else if section == "[Service]"
            && let Some(value) = line.strip_prefix("ExecStart=")
        {
            exec_lines.push(value);
        }
    }
    let line = match exec_lines.as_slice() {
        [line] => *line,
        [] => return Err("no ExecStart= line in [Service]".to_string()),
        _ => return Err("multiple ExecStart= lines in [Service]".to_string()),
    };
    let args = split_exec_args(line).map_err(|err| format!("invalid ExecStart=: {err}"))?;
    let (exe, rest) = args
        .split_first()
        .ok_or_else(|| "empty ExecStart=".to_string())?;
    let specs = match rest.split_first() {
        Some((command, specs)) if command == "start" && !specs.is_empty() => specs,
        _ => return Err("ExecStart= is not `mongoose start SPEC...`".to_string()),
    };
    let specs = specs
        .iter()
        .map(|spec| {
            spec.parse::<ForwardSpec>()
                .map_err(|err| format!("invalid rule '{spec}' in ExecStart=: {err}"))
        })
        .collect::<Result<Vec<_>, _>>()?;
    Ok((PathBuf::from(exe), specs))
}

/// State of the unit file on disk.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum UnitFileStatus {
    Missing,
    /// Symlink to /dev/null.
    Masked,
    Managed {
        exe: PathBuf,
        specs: Vec<ForwardSpec>,
    },
    ManagedButInvalid {
        reason: String,
    },
    /// Not written by `setup`; interpreted on a best-effort basis.
    Foreign {
        link_target: Option<PathBuf>,
        parsed: Result<ParsedUnit, String>,
    },
}

/// Runtime state as reported by `systemctl show`.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct UnitState {
    pub load_state: String,
    pub active_state: String,
    pub sub_state: String,
    pub unit_file_state: String,
    pub result: String,
    pub main_pid: Option<u32>,
    pub active_since: Option<String>,
    pub restarts: Option<u32>,
    pub need_daemon_reload: bool,
}

pub const SHOW_PROPERTIES: &str = "LoadState,ActiveState,SubState,UnitFileState,Result,MainPID,\
                                   ActiveEnterTimestamp,NRestarts,NeedDaemonReload";

impl UnitState {
    /// Parses `KEY=VALUE` lines from `systemctl show`.
    pub fn parse(output: &str) -> Self {
        let mut state = Self::default();
        for line in output.lines() {
            let Some((key, value)) = line.split_once('=') else {
                continue;
            };
            let value = value.trim();
            match key {
                "LoadState" => state.load_state = value.to_string(),
                "ActiveState" => state.active_state = value.to_string(),
                "SubState" => state.sub_state = value.to_string(),
                "UnitFileState" => state.unit_file_state = value.to_string(),
                "Result" => state.result = value.to_string(),
                "MainPID" => state.main_pid = value.parse().ok().filter(|&pid| pid != 0),
                "ActiveEnterTimestamp" if !value.is_empty() && value != "n/a" => {
                    state.active_since = Some(value.to_string());
                }
                "NRestarts" => state.restarts = value.parse().ok(),
                "NeedDaemonReload" => state.need_daemon_reload = value == "yes",
                _ => {}
            }
        }
        state
    }
}

/// Everything `mongoose show` reports.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ShowReport {
    /// The unit file systemd loads, or where `setup` would create one.
    pub path: PathBuf,
    pub file: UnitFileStatus,
    pub conflicts: Vec<UnitConflict>,
    /// `Err` explains why the state is unavailable.
    pub state: Result<UnitState, String>,
    /// System default for IPv6 sockets, used to describe `[::]` rules.
    pub ipv6_dual_stack: bool,
}

fn or_unknown(value: &str) -> &str {
    if value.is_empty() { "unknown" } else { value }
}

impl ShowReport {
    fn write_rules(&self, f: &mut fmt::Formatter<'_>, specs: &[ForwardSpec]) -> fmt::Result {
        for (index, spec) in specs.iter().enumerate() {
            writeln!(f, "  #{} {spec}", index + 1)?;
            writeln!(f, "     {}", spec.describe(self.ipv6_dual_stack))?;
        }
        if let Err(err) = crate::conflict::check(specs, self.ipv6_dual_stack) {
            writeln!(
                f,
                "Warning:      these rules collide; `mongoose start` refuses them"
            )?;
            for conflict in &err.0 {
                writeln!(f, "  {conflict}")?;
            }
        }
        Ok(())
    }
}

impl fmt::Display for ShowReport {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match &self.file {
            UnitFileStatus::Missing => {
                writeln!(
                    f,
                    "Unit file:    none found (setup would create {})",
                    self.path.display()
                )?;
            }
            _ => writeln!(f, "Unit file:    {}", self.path.display())?,
        }
        match &self.file {
            UnitFileStatus::Missing => {}
            UnitFileStatus::Masked => {
                writeln!(f, "Managed:      no (masked: symlink to /dev/null)")?
            }
            UnitFileStatus::ManagedButInvalid { reason } => {
                writeln!(f, "Managed:      yes (written by `mongoose setup`)")?;
                writeln!(f, "Rules:        unreadable: {reason}")?;
            }
            UnitFileStatus::Managed { exe, specs } => {
                writeln!(f, "Managed:      yes (written by `mongoose setup`)")?;
                writeln!(f, "Executable:   {}", exe.display())?;
                writeln!(f, "Rules:")?;
                self.write_rules(f, specs)?;
            }
            UnitFileStatus::Foreign {
                link_target,
                parsed,
            } => {
                writeln!(f, "Managed:      no (not written by `mongoose setup`)")?;
                if let Some(target) = link_target {
                    writeln!(f, "Symlink to:   {}", target.display())?;
                }
                match parsed {
                    Err(reason) => {
                        writeln!(f, "Rules:        cannot interpret the unit: {reason}")?
                    }
                    Ok(unit) => {
                        writeln!(f, "Executable:   {}", unit.exe.display())?;
                        if unit.verbose {
                            writeln!(f, "Verbose:      yes")?;
                        }
                        for note in &unit.notes {
                            writeln!(f, "Note:         {note}")?;
                        }
                        writeln!(f, "Rules (best-effort interpretation):")?;
                        self.write_rules(f, &unit.specs)?;
                    }
                }
            }
        }
        match &self.state {
            Err(reason) => writeln!(f, "State:        unavailable ({reason})")?,
            Ok(state) => {
                writeln!(f, "Loaded:       {}", or_unknown(&state.load_state))?;
                write!(
                    f,
                    "Active:       {} ({})",
                    or_unknown(&state.active_state),
                    or_unknown(&state.sub_state)
                )?;
                if let Some(since) = &state.active_since
                    && state.active_state == "active"
                {
                    write!(f, " since {since}")?;
                }
                writeln!(f)?;
                if !state.result.is_empty() && state.result != "success" {
                    writeln!(f, "Last result:  {}", state.result)?;
                }
                writeln!(f, "Enabled:      {}", or_unknown(&state.unit_file_state))?;
                if let Some(pid) = state.main_pid {
                    writeln!(f, "Main PID:     {pid}")?;
                }
                if let Some(restarts) = state.restarts {
                    writeln!(f, "Restarts:     {restarts}")?;
                }
                if state.need_daemon_reload {
                    writeln!(
                        f,
                        "Note:         unit file changed on disk; systemd still uses the old \
                         version until `systemctl daemon-reload`"
                    )?;
                }
            }
        }
        if !self.conflicts.is_empty() {
            writeln!(f, "Conflicts:")?;
            for conflict in &self.conflicts {
                writeln!(f, "  {conflict}")?;
            }
        }
        write!(
            f,
            "Logs:         see `systemctl status {UNIT_NAME}` or `journalctl -u {UNIT_NAME}`"
        )
    }
}

impl<S: System> ServiceManager<S> {
    fn inspect(path: &Path) -> UnitFileStatus {
        let link_target = fs::symlink_metadata(path)
            .ok()
            .filter(|meta| meta.file_type().is_symlink())
            .and_then(|_| fs::read_link(path).ok());
        if link_target.as_deref() == Some(Path::new("/dev/null")) {
            return UnitFileStatus::Masked;
        }
        let text = match unitfile::read_unit_text(path) {
            Ok(text) => text,
            Err(reason) => {
                return UnitFileStatus::Foreign {
                    link_target,
                    parsed: Err(format!("it {reason}")),
                };
            }
        };
        if link_target.is_none() && is_managed(&text) {
            return match parse_unit(&text) {
                Ok((exe, specs)) => UnitFileStatus::Managed { exe, specs },
                Err(reason) => UnitFileStatus::ManagedButInvalid { reason },
            };
        }
        UnitFileStatus::Foreign {
            link_target,
            parsed: unitfile::parse_foreign_unit(&text),
        }
    }

    /// Collects the unit's configuration and state. Read-only; does not
    /// require root.
    pub fn show(&self) -> Result<ShowReport, ServiceError> {
        let (path, file) = match self.find_units().into_iter().next() {
            None => (self.default_unit_path(), UnitFileStatus::Missing),
            Some(path) => {
                let file = Self::inspect(&path);
                (path, file)
            }
        };
        let state = if self.system.uses_systemd() {
            self.system
                .systemctl(&["show", UNIT_NAME, &format!("--property={SHOW_PROPERTIES}")])
                .map(|output| UnitState::parse(&output))
                .map_err(|err| err.to_string())
        } else {
            Err("systemd is not running".to_string())
        };
        Ok(ShowReport {
            path,
            file,
            conflicts: self.find_conflicts(),
            state,
            ipv6_dual_stack: self.system.ipv6_dual_stack(),
        })
    }
}
