//! systemd unit management for `mongoose setup` and `mongoose remove`.

use std::fmt;
use std::fs;
use std::io::{self, Write};
use std::os::unix::fs::OpenOptionsExt;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

use log::{debug, info, warn};
use thiserror::Error;

use crate::spec::ForwardSpec;

pub const UNIT_NAME: &str = "mongoose.service";
pub const DROP_IN_DIR_NAME: &str = "mongoose.service.d";
pub const DEFAULT_UNIT_DIR: &str = "/etc/systemd/system";
/// Other systemd unit search paths. A `mongoose.service` or drop-in directory
/// in any of them would shadow or silently alter the generated unit.
pub const OTHER_UNIT_DIRS: &[&str] = &[
    "/etc/systemd/system.control",
    "/run/systemd/system.control",
    "/run/systemd/transient",
    "/run/systemd/generator.early",
    "/run/systemd/system",
    "/run/systemd/generator",
    "/usr/local/lib/systemd/system",
    "/usr/lib/systemd/system",
    "/lib/systemd/system",
    "/run/systemd/generator.late",
];
/// First line of every unit written by `mongoose setup`; used to recognise
/// units this tool is allowed to replace or remove.
pub const MARKER: &str = "# Generated by `mongoose setup`. Managed automatically; do not edit.";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum UnitConflictKind {
    /// Another `mongoose.service` file in a different search path.
    OtherUnit,
    /// A `mongoose.service.d` drop-in directory.
    DropIn,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UnitConflict {
    pub path: PathBuf,
    pub kind: UnitConflictKind,
}

impl fmt::Display for UnitConflict {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self.kind {
            UnitConflictKind::OtherUnit => write!(
                f,
                "{}: another {UNIT_NAME} not managed by mongoose",
                self.path.display()
            ),
            UnitConflictKind::DropIn => write!(
                f,
                "{}: drop-in directory that would alter the generated unit",
                self.path.display()
            ),
        }
    }
}

#[derive(Debug, Error)]
pub enum ServiceError {
    #[error("this command must be run as root")]
    NotRoot,
    #[error("systemd does not appear to be running on this system")]
    NoSystemd,
    #[error("{0} exists but was not created by `mongoose setup`; refusing to touch it")]
    NotManaged(PathBuf),
    #[error("{0} does not exist; nothing to remove")]
    NotInstalled(PathBuf),
    #[error("conflicting systemd configuration, remove it first:{}", list(.0))]
    Conflicts(Vec<UnitConflict>),
    #[error("{0} is not a usable executable path")]
    InvalidExecutable(PathBuf),
    #[error("{path}: {reason}")]
    CorruptUnit { path: PathBuf, reason: String },
    #[error("{path}: {error}")]
    Io { path: PathBuf, error: io::Error },
    #[error("`systemctl {command}` failed: {detail}")]
    Systemctl { command: String, detail: String },
}

fn list(conflicts: &[UnitConflict]) -> String {
    conflicts.iter().map(|c| format!("\n  {c}")).collect()
}

/// Access to the parts of the host system the service manager needs.
pub trait System {
    fn is_root(&self) -> bool;
    fn uses_systemd(&self) -> bool;
    /// Runs `systemctl` with `args`, returning its stdout.
    fn systemctl(&self, args: &[&str]) -> Result<String, ServiceError>;
    /// Whether IPv6 sockets are dual-stack by default (for rule descriptions).
    fn ipv6_dual_stack(&self) -> bool;
}

/// The real host system.
pub struct HostSystem;

impl System for HostSystem {
    fn is_root(&self) -> bool {
        crate::sys::is_root()
    }

    fn ipv6_dual_stack(&self) -> bool {
        crate::sys::ipv6_dual_stack_default()
    }

    fn uses_systemd(&self) -> bool {
        // Same check as sd_booted(3), plus systemctl must be available.
        Path::new("/run/systemd/system").is_dir()
            && Command::new("systemctl")
                .arg("--version")
                .stdout(Stdio::null())
                .stderr(Stdio::null())
                .status()
                .is_ok_and(|status| status.success())
    }

    fn systemctl(&self, args: &[&str]) -> Result<String, ServiceError> {
        let command = args.join(" ");
        debug!("running systemctl {command}");
        let output = Command::new("systemctl")
            .args(args)
            .stdin(Stdio::null())
            .output()
            .map_err(|err| ServiceError::Systemctl {
                command: command.clone(),
                detail: err.to_string(),
            })?;
        let stdout = String::from_utf8_lossy(&output.stdout).into_owned();
        for line in String::from_utf8_lossy(&output.stderr).lines() {
            debug!("systemctl: {line}");
        }
        if output.status.success() {
            Ok(stdout)
        } else {
            let stderr = String::from_utf8_lossy(&output.stderr).trim().to_string();
            Err(ServiceError::Systemctl {
                command,
                detail: if stderr.is_empty() {
                    output.status.to_string()
                } else {
                    stderr
                },
            })
        }
    }
}

/// Returns true if `contents` is a unit written by `mongoose setup`.
pub fn is_managed(contents: &str) -> bool {
    contents.lines().next() == Some(MARKER)
}

/// Quotes a single ExecStart argument following systemd's syntax.
pub fn quote_exec_arg(arg: &str) -> String {
    let escaped = arg.replace('%', "%%").replace('$', "$$");
    let plain = !escaped.is_empty()
        && escaped
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || "/._-:[]*+,@=%$".contains(c));
    if plain {
        return escaped;
    }
    let mut quoted = String::with_capacity(escaped.len() + 2);
    quoted.push('"');
    for c in escaped.chars() {
        match c {
            '"' => quoted.push_str("\\\""),
            '\\' => quoted.push_str("\\\\"),
            '\n' => quoted.push_str("\\n"),
            '\t' => quoted.push_str("\\t"),
            c => quoted.push(c),
        }
    }
    quoted.push('"');
    quoted
}

/// Renders the unit file. Only non-default settings are written.
pub fn render_unit(exe: &Path, specs: &[ForwardSpec]) -> String {
    let mut exec = vec![quote_exec_arg(&exe.to_string_lossy()), "start".to_string()];
    exec.extend(specs.iter().map(|spec| quote_exec_arg(&spec.to_string())));
    format!(
        "{MARKER}\n\
         [Unit]\n\
         Description=Mongoose port forwarder\n\
         Wants=network-online.target\n\
         After=network-online.target\n\
         \n\
         [Service]\n\
         ExecStart={}\n\
         Restart=always\n\
         RestartSec=3\n\
         \n\
         [Install]\n\
         WantedBy=multi-user.target\n",
        exec.join(" ")
    )
}

/// What `setup` does (or did) with the unit file.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SetupOutcome {
    Installed,
    Replaced,
}

pub struct ServiceManager<S> {
    system: S,
    unit_dir: PathBuf,
    other_unit_dirs: Vec<PathBuf>,
}

impl ServiceManager<HostSystem> {
    /// Manager for the real system using the standard systemd paths.
    pub fn host() -> Self {
        Self::new(HostSystem, DEFAULT_UNIT_DIR)
            .with_other_unit_dirs(OTHER_UNIT_DIRS.iter().map(PathBuf::from).collect())
    }
}

impl<S: System> ServiceManager<S> {
    pub fn new(system: S, unit_dir: impl Into<PathBuf>) -> Self {
        Self {
            system,
            unit_dir: unit_dir.into(),
            other_unit_dirs: Vec::new(),
        }
    }

    pub fn with_other_unit_dirs(mut self, dirs: Vec<PathBuf>) -> Self {
        self.other_unit_dirs = dirs;
        self
    }

    pub fn system(&self) -> &S {
        &self.system
    }

    pub fn unit_path(&self) -> PathBuf {
        self.unit_dir.join(UNIT_NAME)
    }

    fn check_environment(&self) -> Result<(), ServiceError> {
        if !self.system.is_root() {
            return Err(ServiceError::NotRoot);
        }
        if !self.system.uses_systemd() {
            return Err(ServiceError::NoSystemd);
        }
        Ok(())
    }

    /// Finds unit files and drop-ins elsewhere that would shadow or modify ours.
    pub fn find_conflicts(&self) -> Vec<UnitConflict> {
        let exists = |path: &Path| fs::symlink_metadata(path).is_ok();
        let mut conflicts = Vec::new();
        for dir in std::iter::once(&self.unit_dir).chain(&self.other_unit_dirs) {
            let unit = dir.join(UNIT_NAME);
            if dir != &self.unit_dir && exists(&unit) {
                conflicts.push(UnitConflict {
                    path: unit,
                    kind: UnitConflictKind::OtherUnit,
                });
            }
            let drop_in = dir.join(DROP_IN_DIR_NAME);
            if exists(&drop_in) {
                conflicts.push(UnitConflict {
                    path: drop_in,
                    kind: UnitConflictKind::DropIn,
                });
            }
        }
        conflicts
    }

    /// Returns whether our unit file exists, failing if something exists at
    /// its path that was not written by `setup`.
    fn existing_managed_unit(&self) -> Result<bool, ServiceError> {
        let path = self.unit_path();
        match fs::symlink_metadata(&path) {
            Err(err) if err.kind() == io::ErrorKind::NotFound => return Ok(false),
            Err(source) => {
                return Err(ServiceError::Io {
                    path,
                    error: source,
                });
            }
            // Symlinks (e.g. a masked unit), directories etc. are never ours.
            Ok(meta) if !meta.file_type().is_file() => return Err(ServiceError::NotManaged(path)),
            Ok(_) => {}
        }
        match fs::read_to_string(&path) {
            Ok(contents) if is_managed(&contents) => Ok(true),
            Ok(_) => Err(ServiceError::NotManaged(path)),
            Err(err) if err.kind() == io::ErrorKind::InvalidData => {
                Err(ServiceError::NotManaged(path))
            }
            Err(source) => Err(ServiceError::Io {
                path,
                error: source,
            }),
        }
    }

    /// Runs every check `setup` performs before touching anything.
    pub fn precheck_setup(&self, exe: &Path) -> Result<SetupOutcome, ServiceError> {
        self.check_environment()?;
        if !exe.is_absolute() || !exe.is_file() {
            return Err(ServiceError::InvalidExecutable(exe.to_path_buf()));
        }
        let conflicts = self.find_conflicts();
        if !conflicts.is_empty() {
            return Err(ServiceError::Conflicts(conflicts));
        }
        Ok(if self.existing_managed_unit()? {
            SetupOutcome::Replaced
        } else {
            SetupOutcome::Installed
        })
    }

    /// Writes the unit and, unless `skip_enable`, reloads systemd, enables
    /// the unit and (re)starts it.
    pub fn setup(
        &self,
        exe: &Path,
        specs: &[ForwardSpec],
        skip_enable: bool,
    ) -> Result<SetupOutcome, ServiceError> {
        let outcome = self.precheck_setup(exe)?;
        let path = self.unit_path();
        if outcome == SetupOutcome::Replaced {
            info!("replacing existing unit {}", path.display());
        }

        write_atomically(&path, &render_unit(exe, specs))?;
        info!("wrote {}", path.display());

        if skip_enable {
            info!("skipping systemd reload and enabling {UNIT_NAME}");
            return Ok(outcome);
        }
        self.system.systemctl(&["daemon-reload"])?;
        self.system.systemctl(&["enable", UNIT_NAME])?;
        // restart also starts a stopped unit and applies a replaced config.
        self.system.systemctl(&["restart", UNIT_NAME])?;
        info!("{UNIT_NAME} enabled and started");
        Ok(outcome)
    }

    /// Runs every check `remove` performs before touching anything.
    pub fn precheck_remove(&self) -> Result<(), ServiceError> {
        self.check_environment()?;
        if !self.existing_managed_unit()? {
            return Err(ServiceError::NotInstalled(self.unit_path()));
        }
        // Another unit with our name would silently take over once ours is
        // gone. Drop-ins are merely left orphaned, which is harmless.
        let (other_units, drop_ins): (Vec<_>, Vec<_>) = self
            .find_conflicts()
            .into_iter()
            .partition(|c| c.kind == UnitConflictKind::OtherUnit);
        if !other_units.is_empty() {
            return Err(ServiceError::Conflicts(other_units));
        }
        for drop_in in drop_ins {
            warn!("{drop_in}; it is not managed by mongoose and will be left in place");
        }
        Ok(())
    }

    /// Stops, disables and deletes the unit written by `setup`.
    pub fn remove(&self) -> Result<(), ServiceError> {
        self.precheck_remove()?;
        let path = self.unit_path();
        self.system.systemctl(&["stop", UNIT_NAME])?;
        self.system.systemctl(&["disable", UNIT_NAME])?;
        fs::remove_file(&path).map_err(|source| ServiceError::Io {
            path: path.clone(),
            error: source,
        })?;
        info!("removed {}", path.display());
        self.system.systemctl(&["daemon-reload"])?;
        Ok(())
    }
}

fn write_atomically(path: &Path, contents: &str) -> Result<(), ServiceError> {
    let io_err = |path: &Path| {
        let path = path.to_path_buf();
        move |source| ServiceError::Io {
            path,
            error: source,
        }
    };
    let tmp = path.with_extension("service.tmp");
    let mut file = fs::OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(true)
        .mode(0o644)
        .open(&tmp)
        .map_err(io_err(&tmp))?;
    file.write_all(contents.as_bytes())
        .and_then(|()| file.sync_all())
        .map_err(io_err(&tmp))?;
    drop(file);
    fs::rename(&tmp, path).map_err(io_err(path))
}

/// Splits a systemd command line into arguments, undoing [`quote_exec_arg`].
/// Only the syntax `quote_exec_arg` produces is accepted.
pub fn split_exec_args(line: &str) -> Result<Vec<String>, String> {
    let mut args = Vec::new();
    let mut chars = line.chars().peekable();
    loop {
        while chars.next_if(|c| c.is_ascii_whitespace()).is_some() {}
        let Some(&first) = chars.peek() else {
            return Ok(args);
        };
        let mut arg = String::new();
        let quoted = first == '"';
        if quoted {
            chars.next();
        }
        loop {
            let c = match chars.next() {
                None if quoted => return Err("unterminated quote".to_string()),
                None => break,
                Some(c) => c,
            };
            match c {
                '"' if quoted => {
                    if chars.peek().is_some_and(|c| !c.is_ascii_whitespace()) {
                        return Err("unexpected text after closing quote".to_string());
                    }
                    break;
                }
                c if !quoted && c.is_ascii_whitespace() => break,
                '\\' if quoted => match chars.next() {
                    Some('"') => arg.push('"'),
                    Some('\\') => arg.push('\\'),
                    Some('n') => arg.push('\n'),
                    Some('t') => arg.push('\t'),
                    other => return Err(format!("unsupported escape \\{}", other.unwrap_or(' '))),
                },
                '%' | '$' => {
                    if chars.next() != Some(c) {
                        return Err(format!("unsupported '{c}' expansion"));
                    }
                    arg.push(c);
                }
                '"' | '\'' | '\\' | ';' => return Err(format!("unexpected '{c}'")),
                c => arg.push(c),
            }
        }
        args.push(arg);
    }
}

/// Extracts the executable and rules from a unit written by [`render_unit`].
pub fn parse_unit(contents: &str) -> Result<(PathBuf, Vec<ForwardSpec>), String> {
    let mut section = "";
    let mut exec_lines = Vec::new();
    for line in contents.lines() {
        let line = line.trim();
        if line.starts_with('[') && line.ends_with(']') {
            section = line;
        } else if section == "[Service]"
            && let Some(value) = line.strip_prefix("ExecStart=")
        {
            exec_lines.push(value);
        }
    }
    let line = match exec_lines.as_slice() {
        [line] => *line,
        [] => return Err("no ExecStart= line in [Service]".to_string()),
        _ => return Err("multiple ExecStart= lines in [Service]".to_string()),
    };
    let args = split_exec_args(line).map_err(|err| format!("invalid ExecStart=: {err}"))?;
    let (exe, rest) = args
        .split_first()
        .ok_or_else(|| "empty ExecStart=".to_string())?;
    let specs = match rest.split_first() {
        Some((command, specs)) if command == "start" && !specs.is_empty() => specs,
        _ => return Err("ExecStart= is not `mongoose start SPEC...`".to_string()),
    };
    let specs = specs
        .iter()
        .map(|spec| {
            spec.parse::<ForwardSpec>()
                .map_err(|err| format!("invalid rule '{spec}' in ExecStart=: {err}"))
        })
        .collect::<Result<Vec<_>, _>>()?;
    Ok((PathBuf::from(exe), specs))
}

/// State of the unit file on disk.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum UnitFileStatus {
    Missing,
    NotManaged,
    Managed {
        exe: PathBuf,
        specs: Vec<ForwardSpec>,
    },
    ManagedButInvalid {
        reason: String,
    },
}

/// Runtime state as reported by `systemctl show`.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct UnitState {
    pub load_state: String,
    pub active_state: String,
    pub sub_state: String,
    pub unit_file_state: String,
    pub result: String,
    pub main_pid: Option<u32>,
    pub active_since: Option<String>,
    pub restarts: Option<u32>,
    pub need_daemon_reload: bool,
}

pub const SHOW_PROPERTIES: &str = "LoadState,ActiveState,SubState,UnitFileState,Result,MainPID,\
                                   ActiveEnterTimestamp,NRestarts,NeedDaemonReload";

impl UnitState {
    /// Parses `KEY=VALUE` lines from `systemctl show`.
    pub fn parse(output: &str) -> Self {
        let mut state = Self::default();
        for line in output.lines() {
            let Some((key, value)) = line.split_once('=') else {
                continue;
            };
            let value = value.trim();
            match key {
                "LoadState" => state.load_state = value.to_string(),
                "ActiveState" => state.active_state = value.to_string(),
                "SubState" => state.sub_state = value.to_string(),
                "UnitFileState" => state.unit_file_state = value.to_string(),
                "Result" => state.result = value.to_string(),
                "MainPID" => state.main_pid = value.parse().ok().filter(|&pid| pid != 0),
                "ActiveEnterTimestamp" if !value.is_empty() && value != "n/a" => {
                    state.active_since = Some(value.to_string());
                }
                "NRestarts" => state.restarts = value.parse().ok(),
                "NeedDaemonReload" => state.need_daemon_reload = value == "yes",
                _ => {}
            }
        }
        state
    }
}

/// Everything `mongoose show` reports.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ShowReport {
    pub path: PathBuf,
    pub file: UnitFileStatus,
    pub conflicts: Vec<UnitConflict>,
    /// `Err` explains why the state is unavailable.
    pub state: Result<UnitState, String>,
    /// System default for IPv6 sockets, used to describe `[::]` rules.
    pub ipv6_dual_stack: bool,
}

fn or_unknown(value: &str) -> &str {
    if value.is_empty() { "unknown" } else { value }
}

impl fmt::Display for ShowReport {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        writeln!(f, "Unit file:    {}", self.path.display())?;
        match &self.file {
            UnitFileStatus::Missing => writeln!(f, "Managed:      no (file does not exist)")?,
            UnitFileStatus::NotManaged => {
                writeln!(f, "Managed:      no (not written by `mongoose setup`)")?;
            }
            UnitFileStatus::ManagedButInvalid { reason } => {
                writeln!(f, "Managed:      yes (written by `mongoose setup`)")?;
                writeln!(f, "Rules:        unreadable: {reason}")?;
            }
            UnitFileStatus::Managed { exe, specs } => {
                writeln!(f, "Managed:      yes (written by `mongoose setup`)")?;
                writeln!(f, "Executable:   {}", exe.display())?;
                writeln!(f, "Rules:")?;
                for (index, spec) in specs.iter().enumerate() {
                    writeln!(f, "  #{} {spec}", index + 1)?;
                    writeln!(f, "     {}", spec.describe(self.ipv6_dual_stack))?;
                }
            }
        }
        match &self.state {
            Err(reason) => writeln!(f, "State:        unavailable ({reason})")?,
            Ok(state) => {
                writeln!(f, "Loaded:       {}", or_unknown(&state.load_state))?;
                write!(
                    f,
                    "Active:       {} ({})",
                    or_unknown(&state.active_state),
                    or_unknown(&state.sub_state)
                )?;
                if let Some(since) = &state.active_since
                    && state.active_state == "active"
                {
                    write!(f, " since {since}")?;
                }
                writeln!(f)?;
                if !state.result.is_empty() && state.result != "success" {
                    writeln!(f, "Last result:  {}", state.result)?;
                }
                writeln!(f, "Enabled:      {}", or_unknown(&state.unit_file_state))?;
                if let Some(pid) = state.main_pid {
                    writeln!(f, "Main PID:     {pid}")?;
                }
                if let Some(restarts) = state.restarts {
                    writeln!(f, "Restarts:     {restarts}")?;
                }
                if state.need_daemon_reload {
                    writeln!(
                        f,
                        "Note:         unit file changed on disk; systemd still uses the old \
                         version until `systemctl daemon-reload`"
                    )?;
                }
            }
        }
        if !self.conflicts.is_empty() {
            writeln!(f, "Conflicts:")?;
            for conflict in &self.conflicts {
                writeln!(f, "  {conflict}")?;
            }
        }
        write!(
            f,
            "Logs:         see `systemctl status {UNIT_NAME}` or `journalctl -u {UNIT_NAME}`"
        )
    }
}

impl<S: System> ServiceManager<S> {
    /// Collects the unit's configuration and state. Read-only; does not
    /// require root.
    pub fn show(&self) -> Result<ShowReport, ServiceError> {
        let path = self.unit_path();
        let file = match self.existing_managed_unit() {
            Ok(false) => UnitFileStatus::Missing,
            Err(ServiceError::NotManaged(_)) => UnitFileStatus::NotManaged,
            Err(err) => return Err(err),
            Ok(true) => {
                let contents = fs::read_to_string(&path).map_err(|source| ServiceError::Io {
                    path: path.clone(),
                    error: source,
                })?;
                match parse_unit(&contents) {
                    Ok((exe, specs)) => UnitFileStatus::Managed { exe, specs },
                    Err(reason) => UnitFileStatus::ManagedButInvalid { reason },
                }
            }
        };
        let state = if self.system.uses_systemd() {
            self.system
                .systemctl(&["show", UNIT_NAME, &format!("--property={SHOW_PROPERTIES}")])
                .map(|output| UnitState::parse(&output))
                .map_err(|err| err.to_string())
        } else {
            Err("systemd is not running".to_string())
        };
        Ok(ShowReport {
            path,
            file,
            conflicts: self.find_conflicts(),
            state,
            ipv6_dual_stack: self.system.ipv6_dual_stack(),
        })
    }
}
